"""Join the extra facts in tools/more_facts/*.json into ../morefacts.js.

Each file maps "world/kind" to places, and each place to [English facts, German facts], six of each,
or five where a place already had three, so every place ends up with eight:
{"earth/country": {"Algeria": [["...", ...], ["...", ...]]}}
The game adds these to the facts each place already has and shows two of them at random each round.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent / "morefacts.js"

facts = {}
for path in sorted((HERE / "more_facts").glob("*.json")):
    for group, places in json.loads(path.read_text(encoding="utf8")).items():
        for name, (en, de) in places.items():
            key = f"{group}/{name}"
            assert key not in facts, f"{key} appears twice ({path.name})"
            assert len(en) == len(de) and len(en) in (5, 6, 7), f"{key} needs five to seven facts in each language ({path.name})"
            facts[key] = [en, de]
OUT.write_text("/* Generated by tools/build_more_facts.py from tools/more_facts/. Extra facts per place: [English, German]. */\n"
               f"window.BLANK_MAP_MORE_FACTS = {json.dumps(facts, ensure_ascii=False, separators=(',', ':'))};\n", encoding="utf8")
print(len(facts), "places,", sum(len(en) + len(de) for en, de in facts.values()), "facts; wrote", OUT, OUT.stat().st_size // 1024, "KB")
