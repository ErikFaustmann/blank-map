"""Join tools/water_content.py with Natural Earth outlines and write ../water.js.

Usage: python -I build_water.py <dir with ne_50m_geography_marine_polys.geojson and ne_50m_lakes.geojson>

It also keeps every lake from the lake file, simplified, so the world map can show lakes as water.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import water_content as content  # noqa: E402

RAW = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(__file__).parent.parent / "water.js"
# Degrees: oceans are huge and can be rough, lakes are small and need detail.
TOLERANCE = {"Oceans": .2, "sea": .04, "lake": .012}


def simplify(points, tolerance):
    """Douglas-Peucker in degrees, which is plenty for a quiz map."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    length = (dx * dx + dy * dy) ** .5 or 1e-12
    far, index = 0, 0
    for i in range(1, len(points) - 1):
        x, y = points[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / length
        if d > far:
            far, index = d, i
    if far <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[:index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def load(name):
    return json.loads((RAW / name).read_text(encoding="utf8"))["features"]


def polygons(geometry):
    return [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"] if geometry["type"] == "MultiPolygon" else []


def tidy(polygon, tolerance):
    """Simplifies each ring and drops the ones too small to keep their shape."""
    rings = []
    for ring in polygon:
        # A closed ring starts and ends at the same point, so it is simplified as two halves.
        flat = [[x, y] for x, y, *_ in ring]
        middle = len(flat) // 2
        points = simplify(flat[:middle + 1], tolerance)[:-1] + simplify(flat[middle:], tolerance)
        if len(points) >= 4:
            if points[0] != points[-1]:
                points.append(points[0])
            rings.append([[round(x, 3), round(y, 3)] for x, y in points])
    return rings if rings and len(polygon[0]) and rings[0] else None


marine, lakes = load("ne_50m_geography_marine_polys.geojson"), load("ne_50m_lakes.geojson")
by_name = {}
for f in marine + lakes:
    by_name.setdefault(f["properties"].get("name") or "", []).append(f)

waters = []
for name, (de, aliases, tier, region, ne_names, facts) in content.WATERS.items():
    found = [f for n in ne_names for f in by_name.get(n, [])]
    missing = [n for n in ne_names if n not in by_name]
    assert not missing, (name, missing)
    is_lake = all(f["properties"].get("featurecla", "").lower().startswith(("lake", "reservoir", "alkaline")) for f in found)
    tolerance = TOLERANCE["Oceans"] if region == "Oceans" else TOLERANCE["lake" if is_lake else "sea"]
    shape = [p for f in found for poly in polygons(f["geometry"]) if (p := tidy(poly, tolerance))]
    waters.append({"en": name, "de": de, "aliases": aliases, "tier": tier, "region": region, "lake": is_lake, "shape": shape,
                   "facts": [[en for en, _ in facts], [de_ for _, de_ in facts]]})
    print(f"{name}: {len(shape)} parts, {sum(len(r) for p in shape for r in p)} points")

def visible(polygon):
    """Lakes smaller than about 20 km across would be specks on the map."""
    xs, ys = [x for x, *_ in polygon[0]], [y for _, y, *_ in polygon[0]]
    return max(max(xs) - min(xs), max(ys) - min(ys)) > .2


drawn = [p for f in lakes for poly in polygons(f["geometry"]) if visible(poly) and (p := tidy(poly, .02))]
data = {"waters": waters, "lakes": drawn}
OUT.write_text("/* Generated by tools/build_water.py from tools/water_content.py and Natural Earth outlines (public domain). */\n"
               f"window.BLANK_MAP_WATER = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n", encoding="utf8")
print(len(drawn), "lakes to draw; wrote", OUT, OUT.stat().st_size // 1024, "KB")
