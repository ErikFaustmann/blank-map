"""Look up the coordinates of every sight in tools/sights_content.py on Wikidata and write ../sights.js.

Usage: python -I build_sights.py

Run tools/build_images.py afterwards, so the sights get their photos too.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import build_images as wiki  # noqa: E402
import sights_content as content  # noqa: E402

OUT = pathlib.Path(__file__).parent.parent / "sights.js"


def coordinates(qids):
    """The coordinate location (P625) of each Wikidata item, as [longitude, latitude]."""
    values = " ".join(f"wd:{q}" for q in qids)
    data = wiki.get("https://query.wikidata.org/sparql", {"query": f"SELECT ?item ?at WHERE {{ VALUES ?item {{ {values} }} ?item wdt:P625 ?at }}", "format": "json"})
    out = {}
    for row in data["results"]["bindings"]:
        lon, lat = row["at"]["value"][len("Point("):-1].split()
        out.setdefault(row["item"]["value"].rsplit("/", 1)[1], [round(float(lon), 4), round(float(lat), 4)])
    return out


def main():
    worlds = {"earth": content.EARTH, "usa": content.USA}
    items = [(world, "sight", name, [entry[5]]) for world, sights in worlds.items() for name, entry in sights.items()]
    pages = wiki.resolve(items)
    qids = {key: page["pageprops"]["wikibase_item"] for key, page in pages.items() if "wikibase_item" in page.get("pageprops", {})}
    found = coordinates(sorted(set(qids.values())))
    out = {}
    for world, sights in worlds.items():
        for name, (de, aliases, tier, region, home, title, zero, facts) in sights.items():
            at = found.get(qids.get((world, "sight", name)))
            if not at:
                print("no coordinates:", world, name)
                continue
            out.setdefault(world, []).append({"en": name, "de": de, "aliases": aliases, "tier": tier, "region": region, "home": home,
                                              "title": title, "at": at, "zero": zero, "facts": [[en for en, _ in facts], [d for _, d in facts]]})
    OUT.write_text("/* Generated by tools/build_sights.py from tools/sights_content.py, with coordinates from Wikidata (CC0). */\n"
                   f"window.BLANK_MAP_SIGHTS = {json.dumps(out, ensure_ascii=False, separators=(',', ':'))};\n", encoding="utf8")
    print({w: len(s) for w, s in out.items()}, "sights; wrote", OUT)


if __name__ == "__main__":
    main()
